import os
import json
import requests

API_KEY = os.environ.get("OPENROUTER_API_KEY", "")
MODEL_ID = "meta-llama/llama-4-maverick:free"

headers = {
    "Authorization": f"Bearer {API_KEY}",
    "Content-Type": "application/json",
    # Optional headers to show up on openrouter.ai rankings
    "HTTP-Referer": "http://localhost:3000",
    "X-Title": "Local Test Script",
}

payload = {
    "model": MODEL_ID,
    "messages": [
        {
            "role": "user",
            "content": "Confirm your identity: What is your exact model name and creator?",
        }
    ],
}

response = requests.post(
    url="https://openrouter.ai/api/v1/chat/completions",
    headers=headers,
    data=json.dumps(payload),
)

if response.status_code == 200:
    data = response.json()

    # 1. Exact model that served the request
    returned_model = data.get("model")

    # 2. Output generated by the model
    reply = data["choices"][0]["message"]["content"]

    print("--- Verification Details ---")
    print(f"Status Code     : {response.status_code} OK")
    print(f"Verified Model  : {returned_model}")
    print(f"Tokens Used     : {data.get('usage', {})}")
    print("\n--- Model Response ---")
    print(reply)
else:
    print(f"Request failed with status {response.status_code}:")
    print(response.text)
